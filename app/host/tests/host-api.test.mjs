// ujwalam-host API tests against a real host process (libobs, test card project, no devices, no previews).
//   node --test app/host/tests/
// Needs the built host (node app/host/tools/build.mjs) and the OBS runtime (app/host/host.local.json or env).
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync } from 'node:fs';
import path from 'node:path';
import { launchHost, stopHost } from '../lib/launch.mjs';
import { rawRequest, HostClient } from '../lib/client.mjs';
import { REPO_ROOT, HOST_DIR } from '../lib/config.mjs';

const OUT = path.join(REPO_ROOT, 'out', 'host', 'tests');
let h;
let c;

before(async () => {
  const { mkdirSync } = await import('node:fs');
  mkdirSync(OUT, { recursive: true });
  h = await launchHost({
    dataDir: mkdtempSync(path.join(OUT, 'data-')),
    project: path.join(HOST_DIR, 'projects', 'test-card.project.json')
  });
  c = h.client;
});

after(async () => {
  if (!h) return;
  const r = await stopHost(h);
  assert.equal(r.code, 0, 'host exits 0 on host.shutdown');
  assert.equal(existsSync(h.discovery), false, 'discovery file removed on clean shutdown');
});

async function rpcErr(method, params) {
  try {
    await c.call(method, params);
  } catch (e) {
    return e;
  }
  assert.fail(`${method} should have failed`);
}

function post(headers, body = '{"jsonrpc":"2.0","id":1,"method":"host.info"}', extra = {}) {
  const port = h.discoveryJson.port;
  return rawRequest({
    port,
    body,
    headers: {
      Host: `127.0.0.1:${port}`,
      Authorization: `Bearer ${h.token}`,
      'Content-Type': 'application/json',
      'Content-Length': Buffer.byteLength(body),
      ...headers
    },
    ...extra
  });
}

test('discovery: env token is not written, pid matches, owner-only DACL', () => {
  const d = h.discoveryJson;
  assert.equal(d.token, null);
  assert.match(d.systemToken, /^[0-9a-f]{64}$/); // generated by the host, so it is in the file
  assert.equal(d.pid, h.child.pid);
  assert.equal(d.path, '/rpc');
  const ps = spawnSync('powershell', ['-NoProfile', '-Command',
    `$a = Get-Acl -LiteralPath '${h.discovery.replaceAll("'", "''")}'; "$($a.AreAccessRulesProtected) $($a.Access.Count) $($a.Access[0].FileSystemRights)"`],
  { encoding: 'utf8' });
  assert.equal(ps.stdout.trim(), 'True 1 FullControl', ps.stderr);
});

test('listens on 127.0.0.1 only', () => {
  const port = h.discoveryJson.port;
  const ns = spawnSync('netstat', ['-ano', '-p', 'TCP'], { encoding: 'utf8' }).stdout;
  const lines = ns.split(/\r?\n/).filter((l) => l.includes('LISTENING') && new RegExp(`:${port}\\s`).test(l) && l.trim().endsWith(String(h.child.pid)));
  assert.ok(lines.length >= 1, 'listening socket found');
  for (const l of lines) assert.match(l, new RegExp(`\\s127\\.0\\.0\\.1:${port}\\s`));
});

test('HTTP refusals (no body read before auth)', async () => {
  const port = h.discoveryJson.port;
  const body = '{"jsonrpc":"2.0","id":1,"method":"host.info"}';
  const base = { Host: `127.0.0.1:${port}`, Authorization: `Bearer ${h.token}`, 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(body) };
  const without = (k) => Object.fromEntries(Object.entries(base).filter(([x]) => x !== k));
  const cases = [
    ['missing Authorization', without('Authorization'), 401],
    ['wrong token', { ...base, Authorization: 'Bearer ' + '0'.repeat(64) }, 401],
    ['Basic scheme', { ...base, Authorization: `Basic ${h.token}` }, 401],
    ['foreign Host', { ...base, Host: `evil.example:${port}` }, 403],
    ['wrong port in Host', { ...base, Host: `127.0.0.1:${port + 1}` }, 403],
    ['Origin present', { ...base, Origin: 'http://127.0.0.1' }, 403],
    ['Sec-Fetch present', { ...base, 'Sec-Fetch-Mode': 'cors' }, 403],
    ['text/plain', { ...base, 'Content-Type': 'text/plain' }, 415]
  ];
  for (const [name, headers, status] of cases) {
    const r = await rawRequest({ port, body, headers });
    assert.equal(r.status, status, name);
  }
  const auth = { Host: `127.0.0.1:${port}`, Authorization: `Bearer ${h.token}` };
  assert.equal((await rawRequest({ port, method: 'GET', headers: auth })).status, 405);
  assert.equal((await rawRequest({ port, path: '/', headers: auth })).status, 404);
  assert.equal((await rawRequest({ port, path: '/rpc?x=1', headers: auth })).status, 400);
  const big = JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'host.info', params: { x: 'a'.repeat((1 << 20) + 16) } }); // limit: 1 MiB
  assert.equal((await post({}, big)).status, 413);
});

test('JSON-RPC errors', async () => {
  let r = await post({}, '{not json');
  assert.equal(JSON.parse(r.body).error.code, -32700);
  r = await post({}, '[{"jsonrpc":"2.0","id":1,"method":"host.info"}]');
  assert.equal(JSON.parse(r.body).error.code, -32600);
  r = await post({}, '{"jsonrpc":"2.0","id":1,"method":"host.info","extra":1}');
  assert.equal(JSON.parse(r.body).error.code, -32600);
  r = await post({}, '{"jsonrpc":"2.0","id":1,"method":"host.info","method":"x"}');
  assert.equal(JSON.parse(r.body).error.code, -32700, 'duplicate keys refused');
  assert.equal((await rpcErr('no.such.method')).code, -32601);
  assert.equal((await rpcErr('host.info', { unexpected: true })).code, -32602);
  assert.equal((await rpcErr('scenes.activate', { scene: 42 })).code, -32602);
});

