test('host.info / host.status contract (UI fields)', async () => {
  const info = await c.call('host.info');
  assert.equal(info.flags.allowDevices, false);
  for (const m of ['win-dshow', 'win-wasapi', 'obs-browser', 'rtmp-services', 'win-capture', 'obs-websocket'])
    assert.ok(info.disabledModules.includes(m), `${m} disabled`);
  assert.ok('gpuPreference' in info);
  const st = await c.call('host.status');
  for (const k of ['live', 'recording', 'droppedFrames', 'totalFrames', 'fps', 'cpuPct', 'gpuPct', 'outputsReady'])
    assert.ok(k in st, `host.status.${k}`);
  assert.deepEqual(Object.keys(st.outputsReady).sort(), ['record', 'stream']);
  assert.equal(st.live, false);
  assert.equal(st.recording, false);
});

test('scenes and layers: list, activate, case-insensitive canvas, visibility, move', async () => {
  const l = await c.call('scenes.list', { canvas: 'h' });
  assert.ok(l.scenes.some((s) => s.id === 'card-h'));
  await c.call('scenes.activate', { scene: 'plain-h' });
  await c.call('scenes.activate', { scene: 'card-h' });
  let ls = await c.call('layers.list', { scene: 'card-h' });
  assert.deepEqual(ls.layers.map((x) => x.id), ['bg', 'bars', 'motion']);
  await c.call('layers.setVisible', { scene: 'card-h', layer: 'motion', visible: false });
  await c.call('layers.move', { scene: 'card-h', layer: 'motion', direction: 'bottom' });
  ls = await c.call('layers.list', { scene: 'card-h' });
  assert.deepEqual(ls.layers.map((x) => x.id), ['motion', 'bg', 'bars']);
  assert.equal(ls.layers[0].visible, false);
  await c.call('layers.move', { scene: 'card-h', layer: 'motion', index: 2 });
  await c.call('layers.setVisible', { scene: 'card-h', layer: 'motion', visible: true });
  ls = await c.call('layers.list', { scene: 'card-h' });
  assert.deepEqual(ls.layers.map((x) => x.id), ['bg', 'bars', 'motion']);
  assert.equal((await rpcErr('layers.move', { scene: 'card-h', layer: 'motion', index: 0, direction: 'up' })).code, -32602);
  await c.call('layers.add', { scene: 'plain-h', layer: { id: 'c2', type: 'color', settings: { color: '#FF00FF00' } } });
  await c.call('layers.remove', { scene: 'plain-h', layer: 'c2' });
});

test('devices, browser and non-loopback inputs are refused', async () => {
  for (const type of ['dshow_video', 'wasapi_input'])
    assert.equal((await rpcErr('layers.add', { scene: 'plain-h', layer: { id: 'dev', type, settings: {} } })).code, -32001, type);
  assert.equal((await rpcErr('layers.add', { scene: 'plain-h', layer: { id: 'b', type: 'browser', settings: { url: 'http://127.0.0.1:1/' } } })).code, -32001);
  assert.equal((await rpcErr('layers.add', { scene: 'plain-h', layer: { id: 'm', type: 'media', settings: { file: 'relative.mp4' } } })).code, -32602);
});

const RUNG = { id: 'r', canvas: 'H', codec: 'h264', encoder: 'nvenc', rc: 'cbr', w: 640, h: 360, fps: 30, bitrate: 1500, gopSec: 2 };
const AUDIO = { bitrate: 128, sampleRate: 48000 };
const sink = (target, extra = {}) => ({ id: 's', rung: 'r', platform: 'twitch', proto: 'rtmp', priority: 1, target, ...extra });

test('outputs.configure accepts loopback targets only', async () => {
  const bad = [
    { transport: 'rtmp', port: 19400, app: 'live', stream: 'x', host: 'example.com' },
    { transport: 'rtmp', url: 'rtmp://example.com/live/key' },
    { transport: 'rtmps', port: 19400 },
    { transport: 'rtmp', port: 80, app: 'live', stream: 'x' },
    { transport: 'rtmp', port: 19400, app: 'live/../x', stream: 'x' },
    { transport: 'srt', port: 19400, latencyMs: 120, passphrase: 'p' },
    { transport: 'file', name: '../escape.mkv' },
    { transport: 'file', name: 'C:/x.mkv' },
    { transport: 'file', name: 'x.exe' }
  ];
  for (const t of bad) {
    const proto = t.transport === 'file' ? 'file' : 'rtmp';
    const e = await rpcErr('outputs.configure', { rungs: [RUNG], audio: AUDIO, sinks: [sink(t, { proto, platform: proto === 'file' ? 'local' : 'twitch' })] });
    assert.equal(e.code, -32602, JSON.stringify(t));
  }
  assert.equal((await rpcErr('outputs.configure', { rungs: [RUNG], audio: { bitrate: 128, sampleRate: 44100 }, sinks: [sink({ transport: 'file', name: 'a.mkv' }, { proto: 'file', platform: 'local' })] })).code, -32602, 'sample rate must match the studio');
  assert.equal((await rpcErr('outputs.configure', { rungs: [{ ...RUNG, w: 3840, h: 2160 }], audio: AUDIO, sinks: [sink({ transport: 'file', name: 'a.mkv' }, { proto: 'file', platform: 'local' })] })).code, -32602, 'no upscaling');
  assert.equal((await rpcErr('outputs.configure', { rungs: [{ ...RUNG, fps: 25 }], audio: AUDIO, sinks: [sink({ transport: 'file', name: 'a.mkv' }, { proto: 'file', platform: 'local' })] })).code, -32602, 'fps must divide the canvas fps');
});

test('record start/stop on a file sink; project.load refused while active; stream.start without stream sinks', async () => {
  const conf = await c.call('outputs.configure', { rungs: [RUNG], audio: AUDIO, sinks: [sink({ transport: 'file', name: 'api-test.mkv' }, { id: 'rec', proto: 'file', platform: 'local' })] });
  assert.equal(conf.audio.encoders, 1);
  assert.ok(conf.probe.started >= 1, 'NVENC probed before configure');
  assert.deepEqual((await c.call('host.status')).outputsReady, { stream: false, record: true });
  assert.equal((await rpcErr('stream.start', {})).code, -32009);
  await c.call('record.start', {});
  let st;
  for (let i = 0; i < 40; i++) {
    st = await c.call('outputs.status');
    if (st.sinks[0].state === 'live') break;
    await new Promise((r) => setTimeout(r, 100));
  }
  assert.equal(st.sinks[0].state, 'live');
  assert.equal((await c.call('host.status')).recording, true);
  const got = await c.call('project.get');
  assert.equal(got.format, 'ujwalam-host-test');
  const proj = got.project;
  assert.equal((await rpcErr('project.load', { project: proj })).code, -32009);
  assert.equal((await rpcErr('outputs.configure', { rungs: [RUNG], audio: AUDIO, sinks: [sink({ transport: 'file', name: 'b.mkv' }, { proto: 'file', platform: 'local' })] })).code, -32009);
  await new Promise((r) => setTimeout(r, 1500));
  await c.call('record.stop', {});
  for (let i = 0; i < 50; i++) {
    st = await c.call('outputs.status');
    if (st.sinks[0].state === 'stopped') break;
    await new Promise((r) => setTimeout(r, 100));
  }
  assert.equal(st.sinks[0].state, 'stopped');
  assert.ok(existsSync(st.sinks[0].path), 'recording file written inside the recordings dir');
  assert.ok(path.resolve(st.sinks[0].path).startsWith(path.resolve(h.dataDir, 'recordings')));
  // project reload keeps the graph: released before, rebuilt after
  const re = await c.call('project.load', { project: proj });
  assert.equal(re.outputs.reconfigured, true);
  await c.call('outputs.clear');
});

test('auth failures are rate limited; a valid token still passes', async () => {
  let last;
  for (let i = 0; i < 25; i++) last = await post({ Authorization: 'Bearer ' + 'f'.repeat(64) });
  assert.equal(last.status, 429);
  assert.ok(last.headers['retry-after']);
  assert.equal((await c.call('host.info')).name, 'ujwalam-host');
});
